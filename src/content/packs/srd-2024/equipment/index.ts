  RAW_SRD_2024_EQUIPMENT.map((item) => {
    const stats = EQUIPMENT_STATS[item.id]
    if (stats === undefined) {
      return item
    }

    return {
      ...item,
      ...stats,
      tags: [...(item.tags ?? []), ...(stats.tags ?? [])],
      notes: stats.notes ?? item.notes,
    }
  })

