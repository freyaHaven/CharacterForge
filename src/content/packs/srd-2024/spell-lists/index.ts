function uniqueUnion(...lists: SpellListDefinition[]): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const entry of lists) {
    for (const id of entry.spellIds) {
      if (!seen.has(id)) {
        seen.add(id)
        out.push(id)
      }
    }
  }
  return out
}

