function list(
  slug: string,
  name: string,
  spellIds: string[],
): SpellListDefinition {
  return {
    id: `srd-2024:spell-list:${slug}`,
    editionId: 'srd-2024',
    name,
    spellIds: spellIds.map((id) =>
      id.startsWith('srd-2024:') ? id : `srd-2024:${id}`,
    ),
    source: SRD_2024_SOURCE,
  }
}

